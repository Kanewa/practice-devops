import math


def вычислить_факториал(n: int) -> int:
    """
    Вычисляет факториал числа n с использованием библиотеки math.
    
    Параметры:
        n (int): Неотрицательное целое число.
    
    Возвращает:
        int: Факториал числа n (n!).
    
    Исключения:
        ValueError: Если n отрицательное.
    """
    if n < 0:
        raise ValueError("Факториал определён только для неотрицательных чисел.")
    # math.factorial оптимизирован для работы с большими числами
    return math.factorial(n)


def получить_число_от_пользователя() -> int:
    """
    Запрашивает у пользователя положительное целое число с валидацией ввода.
    Цикл продолжается до тех пор, пока пользователь не введёт корректное значение.
    
    Возвращает:
        int: Введённое пользователем положительное целое число.
    """
    while True:
        ввод = input("Введите положительное целое число: ").strip()
        
        # Проверка: ввод не пустой
        if not ввод:
            print("Ошибка: ввод не может быть пустым. Попробуйте ещё раз.")
            continue
        
        try:
            # Попытка преобразовать строку в целое число
            число = int(ввод)
        except ValueError:
            # Если пользователь ввёл нечисловое значение или дробное число
            print(f"Ошибка: '{ввод}' не является целым числом. Введите целое число.")
            continue
        
        # Проверка: число должно быть положительным (> 0)
        if число <= 0:
            print(f"Ошибка: число должно быть положительным (больше нуля). Вы ввели: {число}.")
            continue
        
        # Если все проверки пройдены — возвращаем число
        return число


def main():
    """
    Главная функция программы: организует запрос числа, вычисление
    факториала и вывод результата.
    """
    print("=" * 50)
    print("  Программа вычисления факториала числа")
    print("=" * 50)
    print("Факториал числа N (обозначается N!) — это произведение")
    print("всех натуральных чисел от 1 до N включительно.")
    print("Например: 5! = 1 × 2 × 3 × 4 × 5 = 120")
    print("-" * 50)
    
    # Запрашиваем число у пользователя с валидацией
    число = получить_число_от_пользователя()
    
    try:
        # Вычисляем факториал
        результат = вычислить_факториал(число)
        
        # Выводим результат
        print("-" * 50)
        print(f"Результат: {число}! = {результат}")
        
        # Дополнительная информация для больших чисел
        if число > 20:
            print(f"(Число содержит {len(str(результат))} цифр)")
            
    except ValueError as e:
        # Обработка неожиданных ошибок валидации
        print(f"Ошибка вычисления: {e}")
    except OverflowError:
        # На случай переполнения (в Python это практически невозможно из-за длинной арифметики,
        # но на других языках это была бы реальная проблема)
        print("Ошибка: число слишком велико для вычисления факториала.")
    
    print("=" * 50)


if __name__ == "__main__":
    # Точка входа в программу
    main()
