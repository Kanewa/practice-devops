"""
Кейс-задача №4 — Игра "Угадай число"
Компьютер загадывает случайное число от 1 до 100, а пользователь
должен его угадать за ограниченное количество попыток.
Игра поддерживает подсказки, валидацию ввода и повторный запуск.
"""

import random


# Константы игры
МИН_ЧИСЛО = 1         # Минимальное возможное число
МАКС_ЧИСЛО = 100      # Максимальное возможное число
МАКС_ПОПЫТОК = 10     # Максимальное количество попыток
ПОРОГ_ПОДСКАЗКИ = 5   # После скольких попыток давать расширенную подсказку


def загадать_число() -> int:
    """
    Генерирует случайное целое число в заданном диапазоне.
    
    Возвращает:
        int: Случайное число от МИН_ЧИСЛО до МАКС_ЧИСЛО включительно.
    """
    return random.randint(МИН_ЧИСЛО, МАКС_ЧИСЛО)


def получить_подсказку_диапазона(загаданное: int, попытка: int) -> str:
    """
    Формирует расширенную подсказку о диапазоне, в котором находится число.
    Подсказка выдаётся после ПОРОГ_ПОДСКАЗКИ попыток.
    
    Параметры:
        загаданное (int): Загаданное число.
        попытка (int): Номер текущей попытки (начиная с 1).
    
    Возвращает:
        str: Строка с подсказкой или пустая строка, если ещё рано.
    """
    if попытка <= ПОРОГ_ПОДСКАЗКИ:
        return ""
    
    # Делим диапазон на четыре равных части и определяем, в какой из них число
    шаг = (МАКС_ЧИСЛО - МИН_ЧИСЛО) // 4
    нижняя = МИН_ЧИСЛО
    верхняя = МИН_ЧИСЛО + шаг

    for _ in range(4):
        if нижняя <= загаданное <= верхняя:
            return f"💡 Подсказка: число находится в диапазоне от {нижняя} до {верхняя}."
        нижняя = верхняя + 1
        верхняя = min(нижняя + шаг - 1, МАКС_ЧИСЛО)

    return ""


def получить_ввод_пользователя(попытка: int, оставшихся: int) -> int | None:
    """
    Запрашивает у пользователя число с полной валидацией ввода.
    Возвращает None, если пользователь хочет выйти.
    
    Параметры:
        попытка (int): Номер текущей попытки.
        оставшихся (int): Количество оставшихся попыток.
    
    Возвращает:
        int | None: Введённое число или None при вводе 'выход'.
    """
    while True:
        подсказка = f"Попытка {попытка}/{МАКС_ПОПЫТОК} (осталось {оставшихся})"
        print(f"\n{подсказка}")
        ввод = input(f"Введите число от {МИН_ЧИСЛО} до {МАКС_ЧИСЛО} (или 'выход' для выхода): ").strip().lower()
        
        # Проверка команды выхода
        if ввод in ("выход", "exit", "q", "quit"):
            return None
        
        # Проверка: ввод не пустой
        if not ввод:
            print("⚠️  Ввод не может быть пустым. Попробуйте ещё раз.")
            continue
        
        # Попытка преобразовать в число
        try:
            число = int(ввод)
        except ValueError:
            print(f"⚠️  '{ввод}' — не целое число. Введите целое число от {МИН_ЧИСЛО} до {МАКС_ЧИСЛО}.")
            continue
        
        # Проверка диапазона
        if не_в_диапазоне(число):
            print(f"⚠️  Число должно быть в диапазоне от {МИН_ЧИСЛО} до {МАКС_ЧИСЛО}.")
            continue
        
        return число


def не_в_диапазоне(число: int) -> bool:
    """
    Проверяет, выходит ли число за допустимый диапазон.
    
    Параметры:
        число (int): Проверяемое число.
    
    Возвращает:
        bool: True если число вне диапазона, False если в диапазоне.
    """
    return число < МИН_ЧИСЛО or число > МАКС_ЧИСЛО


def провести_игру() -> bool:
    """
    Проводит одну партию игры "Угадай число".
    
    Возвращает:
        bool: True если игрок угадал число, False если проиграл или вышел.
    """
    # Загадываем число
    загаданное = загадать_число()
    счётчик_попыток = 0
    
    print("\n" + "🎮 " * 10)
    print(f"Я загадал число от {МИН_ЧИСЛО} до {МАКС_ЧИСЛО}.")
    print(f"У вас {МАКС_ПОПЫТОК} попыток. После {ПОРОГ_ПОДСКАЗКИ}-й попытки — подсказка!")
    print("🎮 " * 10)
    
    while счётчик_попыток < МАКС_ПОПЫТОК:
        счётчик_попыток += 1
        оставшихся = МАКС_ПОПЫТОК - счётчик_попыток + 1
        
        # Получаем ввод пользователя
        догадка = получить_ввод_пользователя(счётчик_попыток, оставшихся)
        
        # Пользователь хочет выйти
        if догадка is None:
            print(f"\n👋 Выход из игры. Загаданное число было: {загаданное}.")
            return False
        
        # Проверяем догадку
        if догадка == загаданное:
            print(f"\n🎉 Поздравляю! Вы угадали число {загаданное}!")
            print(f"Это заняло {счётчик_попыток} {'попытку' if счётчик_попыток == 1 else 'попытки' if 2 <= счётчик_попыток <= 4 else 'попыток'}.")
            return True
        elif догадка < загаданное:
            print("📉 Слишком маленькое! Загаданное число больше.")
        else:
            print("📈 Слишком большое! Загаданное число меньше.")
        
        # Выдаём расширенную подсказку после порогового количества попыток
        подсказка = получить_подсказку_диапазона(загаданное, счётчик_попыток)
        if подсказка:
            print(подсказка)
        
        # Предупреждение о последних попытках
        оставшихся_после = МАКС_ПОПЫТОК - счётчик_попыток
        if оставшихся_после == 2:
            print("⚠️  Осторожно! Осталось всего 2 попытки!")
        elif оставшихся_после == 1:
            print("🚨 Последняя попытка!")
    
    # Попытки закончились
    print(f"\n😞 Попытки закончились! Загаданное число было: {загаданное}.")
    return False


def спросить_повторную_игру() -> bool:
    """
    Спрашивает пользователя, хочет ли он сыграть ещё раз.
    
    Возвращает:
        bool: True если пользователь хочет сыграть снова.
    """
    while True:
        ответ = input("\nХотите сыграть ещё раз? (да/нет): ").strip().lower()
        if ответ in ("да", "д", "yes", "y"):
            return True
        elif ответ in ("нет", "н", "no", "n"):
            return False
        else:
            print("Пожалуйста, введите 'да' или 'нет'.")


def main():
    """
    Главная функция: управляет главным циклом игры, отображает
    общую статистику и приветствует/прощается с пользователем.
    """
    print("=" * 55)
    print("       🎯 ИГРА 'УГАДАЙ ЧИСЛО' 🎯")
    print("=" * 55)
    print("Правила игры:")
    print(f"  • Компьютер загадывает число от {МИН_ЧИСЛО} до {МАКС_ЧИСЛО}")
    print(f"  • У вас {МАКС_ПОПЫТОК} попыток, чтобы его угадать")
    print(f"  • После {ПОРОГ_ПОДСКАЗКИ}-й попытки вы получите подсказку о диапазоне")
    print("  • После каждой попытки — подсказка 'больше' или 'меньше'")
    print("=" * 55)
    
    # Статистика нескольких партий
    всего_игр = 0
    побед = 0
    
    while True:
        всего_игр += 1
        результат = провести_игру()
        if результат:
            побед += 1
        
        # Показываем текущую статистику
        print(f"\n📊 Статистика: побед {побед} из {всего_игр} игр "
              f"({побед * 100 // всего_игр}%)")
        
        # Предлагаем сыграть ещё раз
        if not спросить_повторную_игру():
            break
    
    # Итоговое сообщение
    print("\n" + "=" * 55)
    print(f"Итог: сыграно игр: {всего_игр}, побед: {побед}.")
    if всего_игр > 0:
        процент = побед * 100 // всего_игр
        if процент == 100:
            print("🏆 Превосходно! Вы выиграли все партии!")
        elif процент >= 50:
            print("👍 Неплохо! Продолжайте практиковаться.")
        else:
            print("💪 Не расстраивайтесь, в следующий раз повезёт!")
    print("До свидания! 👋")
    print("=" * 55)


if __name__ == "__main__":
    # Точка входа в программу
    main()
